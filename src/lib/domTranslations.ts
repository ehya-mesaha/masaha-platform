const phraseTranslations: Array<[RegExp, string]> = [
  [/^(\d+|[٠-٩]+)\s*ر\.س$/u, '$1 SAR'],
  [/^ر\.س\s*\/\s*ساعة$/u, 'SAR / hour'],
  [/^ر\.س\s*\/\s*يوم$/u, 'SAR / day'],
  [/^لكل\s+ساعة$/u, 'per hour'],
  [/^لكل\s+يوم$/u, 'per day'],
  [/^(\d+|[٠-٩]+)\s*شخص$/u, '$1 people'],
  [/^الطاقة الاستيعابية:\s*(.+)\s*شخص$/u, 'Capacity: $1 people'],
  [/^الحد الأدنى:\s*(.+)\s*ساعة.*$/u, 'Minimum: $1 hours'],
  [/^سياسة الإلغاء:\s*(.+)$/u, 'Cancellation Policy: $1'],
  [/^الحجز المسبق:\s*حتى\s*(.+)\s*يوم$/u, 'Advance booking: up to $1 days'],
  [/^الحد الأدنى للحجز:\s*(.+)\s*ساعة.*$/u, 'Minimum booking: $1 hours'],
  [/^الشارع:\s*(.+)$/u, 'Street: $1'],
  [/^رقم المبنى:\s*(.+)$/u, 'Building number: $1'],
  [/^الرمز البريدي:\s*(.+)$/u, 'Postal code: $1'],
  [/^معالم قريبة:\s*(.+)$/u, 'Nearby landmarks: $1'],
  [/^(.+)\s+من\s+5$/u, '$1 out of 5'],
  [/^\((.+)\s+تقييم\)$/u, '($1 reviews)'],
  [/^(.+)\s+تقييم موثق$/u, '$1 verified reviews'],
  [/^حجز بتاريخ\s+(.+)$/u, 'Booking on $1'],
]

export function translateDomText(value: string) {
  const trimmed = value.trim()
  if (!trimmed) return value

  let translated = exactTranslations[trimmed]
  if (!translated) {
    for (const [pattern, replacement] of phraseTranslations) {
      if (pattern.test(trimmed)) {
        translated = trimmed.replace(pattern, replacement)
        break
      }
    }
  }

  if (!translated || translated === trimmed) return value
  return value.replace(trimmed, translated)
}
